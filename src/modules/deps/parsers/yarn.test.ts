import { describe, expect, it } from 'vitest'
import { isNonRegistryRange, parseYarnLock, splitSpec } from './yarn.ts'

const CLASSIC = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@babel/code-frame@^7.0.0", "@babel/code-frame@^7.10.4":
  version "7.12.13"
  resolved "https://registry.yarnpkg.com/@babel/code-frame/-/code-frame-7.12.13.tgz#dcfc826beef65e75c50e21d3837d7d95798dd658"
  integrity sha512-HV1Cm0Q3ZrpCR93tkWOYiuYIgLxZXZFVG2VgK+MBWjUqZTundupbfx2aXarXuw5Ko5aMcjtJgbSs4vUGBS5v6g==
  dependencies:
    "@babel/highlight" "^7.12.13"

lodash@^4.17.15, lodash@^4.17.20:
  version "4.17.21"
  resolved "https://registry.yarnpkg.com/lodash/-/lodash-4.17.21.tgz#679591c564c3bffaae8454cf0b3df370c3d6911c"

string-width-cjs@npm:string-width@^4.2.0:
  version "4.2.3"
  resolved "https://registry.yarnpkg.com/string-width/-/string-width-4.2.3.tgz"

my-fork@user/repo#main:
  version "1.0.0"
  resolved "https://codeload.github.com/user/repo/tar.gz/abc"

local@file:./local:
  version "0.0.1"
  resolved "file:./local"
`

const BERRY = `# This file is generated by running "yarn install" inside your project.

__metadata:
  version: 6
  cacheKey: 8

"lodash@npm:^4.17.21, lodash@npm:^4.17.4":
  version: 4.17.21
  resolution: "lodash@npm:4.17.21"
  checksum: eb835a2e51d381e561e508ce932ea50a8e5a68f4ebdd771ea240d3048244a8d13658acbd502cd4829768c56f2e16bdd4340b9ea141297d472517b83868e677f7
  languageName: node
  linkType: hard

"@types/node@npm:*":
  version: 20.10.0
  resolution: "@types/node@npm:20.10.0"

"my-app@workspace:.":
  version: 0.0.0-use.local
  resolution: "my-app@workspace:."
`

describe('parseYarnLock classic', () => {
  const r = parseYarnLock(CLASSIC)
  it('parses scoped and multi-spec entries', () => {
    expect(r.deps).toContainEqual({ name: '@babel/code-frame', version: '7.12.13', ecosystem: 'npm' })
    expect(r.deps).toContainEqual({ name: 'lodash', version: '4.17.21', ecosystem: 'npm' })
  })
  it('resolves npm: aliases to the real package', () => {
    expect(r.deps).toContainEqual({ name: 'string-width', version: '4.2.3', ecosystem: 'npm' })
  })
  it('skips file: dependencies', () => {
    expect(r.deps.find((d) => d.name === 'local')).toBeUndefined()
    expect(r.skipped.map((s) => s.entry)).toEqual(['my-fork@1.0.0', 'local@0.0.1'])
    expect(r.deps.find((d) => d.name === 'my-fork')).toBeUndefined()
  })
  it('does not treat nested dependency lines as entries', () => {
    expect(r.deps.find((d) => d.name === '@babel/highlight')).toBeUndefined()
  })
})

describe('parseYarnLock berry', () => {
  const r = parseYarnLock(BERRY)
  it('uses the resolution field', () => {
    expect(r.deps).toEqual([
      { name: 'lodash', version: '4.17.21', ecosystem: 'npm' },
      { name: '@types/node', version: '20.10.0', ecosystem: 'npm' },
    ])
  })
  it('skips workspaces', () => {
    expect(r.skipped).toEqual([expect.objectContaining({ entry: 'my-app@workspace:.' })])
  })
})

describe('yarn helpers', () => {
  it('splitSpec handles scopes and quotes', () => {
    expect(splitSpec('"@a/b@^1.0.0"')).toEqual({ name: '@a/b', range: '^1.0.0' })
    expect(splitSpec('left-pad@1.3.0')).toEqual({ name: 'left-pad', range: '1.3.0' })
    expect(splitSpec('nope')).toBeNull()
  })
  it('throws on empty input', () => {
    expect(() => parseYarnLock('# yarn lockfile v1\n')).toThrow()
  })
  it('skips GitHub shorthand deps even though they resolve to an https codeload tarball', () => {
    const lock = [
      '# yarn lockfile v1',
      '',
      'my-fork@user/my-fork#v1.0.0:',
      '  version "1.0.0"',
      '  resolved "https://codeload.github.com/user/my-fork/tar.gz/abc123"',
      '',
      'other@github:user/other:',
      '  version "2.0.0"',
      '  resolved "https://codeload.github.com/user/other/tar.gz/def456"',
      '',
      'lodash@^4.17.20:',
      '  version "4.17.21"',
      '  resolved "https://registry.yarnpkg.com/lodash/-/lodash-4.17.21.tgz"',
      '',
    ].join('\n')
    const r = parseYarnLock(lock)
    expect(r.deps).toEqual([{ name: 'lodash', version: '4.17.21', ecosystem: 'npm' }])
    expect(r.skipped.map((s) => s.entry)).toEqual(['my-fork@1.0.0', 'other@2.0.0'])
  })
  it('isNonRegistryRange', () => {
    for (const r of ['user/repo', 'user/repo#main', 'github:u/r', 'git+https://x/y.git', 'https://x/y.tgz', 'file:../x', './x', 'link:../x']) {
      expect(isNonRegistryRange(r)).toBe(true)
    }
    for (const r of ['^1.2.3', '~1.0.0', '1.x', 'latest', '>=1.0.0 <2.0.0', '*', 'npm:string-width@^4.2.0']) {
      expect(isNonRegistryRange(r)).toBe(false)
    }
  })
})
