import type { Checklist, ChecklistItem } from '../types'

/**
 * Curated subset of OWASP ASVS 5.0.0 (released May 2025), Level 1 and 2.
 * Requirement ids, chapter titles and levels were checked against the source text in
 * https://github.com/OWASP/ASVS/tree/master/5.0/en . The reference format "v5.0.0-<chapter>.<section>.<req>"
 * is the one recommended by the ASVS itself. Item text is a short paraphrase — read the source for the exact wording.
 */

/** Build an ASVS item: id and ref are derived from the requirement number so they can never disagree. */
function req(
  num: string,
  level: 1 | 2,
  text: string,
  detail: string,
  extra: { cwe?: string[]; stacks?: ChecklistItem['stacks'] } = {},
): ChecklistItem {
  return {
    id: `asvs-${num}`,
    level,
    text,
    detail,
    refs: [`v5.0.0-${num}`, ...(extra.cwe ?? [])],
    ...(extra.stacks ? { stacks: extra.stacks } : {}),
  }
}

